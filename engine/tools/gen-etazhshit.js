// Продолжение объекта «ВРУ жилого дома»: тот кончается на автоматах стояков,
// а дальше в музее было пусто.
//
//   node tools/gen-etazhshit.js && node build.js --config configs/etazhshit.json
//
// Зачем именно это. Грепом по всем 51 объекту музея: слов «квартирный счётчик»
