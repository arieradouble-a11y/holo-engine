// живут почти все бытовые вопросы: кто чинит, если не работает розетка; откуда
// берётся ОДН; почему нельзя ставить автомат побольше; почему в старой квартире
// у «евророзетки» земля никуда не идёт.
//
// Главное, что показывает объект, — ГРАНИЦА. Она проходит не по входной двери:
// стояк, этажный щит и вводной автомат квартиры — общее имущество дома, и лезть
// туда жителю нельзя (там пломба и чужой ток), а всё, что после вводного
// автомата, — собственность и забота владельца квартиры. Из-за этой границы и
// идут все споры «я вызвал УК, а они говорят — не наше».
//
// ⚠ Компоновка — РАЗРЕЗ ПО ЭТАЖУ, а не комната: плита пола, плита потолка, стена
// площадки со щитом, межквартирная стена с дверью и стена квартиры со щитком,
// линиями и точками. Сплошных коробов нет: в аддитивном каркасе они дают
// двенадцать рёбер и прячут внутренность (урок теплотрассы и лифта).
//
// Система координат: X — вдоль стены (площадка при −X, квартира при +X),
// Y — высота от пола этажа, Z — глубина (лицо стен смотрит в +Z, к зрителю).
