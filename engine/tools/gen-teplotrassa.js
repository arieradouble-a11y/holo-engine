// водопровод, кабельная канализация и канализационный коллектор: при раскопке
// их видят вместе, и именно поэтому теплосети нельзя копать «на глазок».
//
// Система координат: X — вдоль трассы, Y — от поверхности земли (0) вниз,
// Z — поперёк улицы; дом стоит на +Z, к нему идёт ответвление.
//
//   node tools/gen-teplotrassa.js && node build.js --config configs/teplotrassa.json --check
