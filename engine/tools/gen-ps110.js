// Провод: гибкая трасса с провисом. Труба тут была бы враньём — на ОРУ висит
// именно провод, и стрела провеса у него видна невооружённым глазом.
const provod = (a, b, sag, mat) => {
  const m = [(a[0] + b[0]) / 2, (a[1] + b[1]) / 2 - sag, (a[2] + b[2]) / 2];
  const q = [(a[0] + m[0]) / 2, (a[1] + m[1]) / 2 - sag * 0.35, (a[2] + m[2]) / 2];
  const w = [(m[0] + b[0]) / 2, (m[1] + b[1]) / 2 - sag * 0.35, (m[2] + b[2]) / 2];
  return [{ tube: [0.035, [a, q, m, w, b], mat, 6] }];
};

