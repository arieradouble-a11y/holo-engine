// Генератор configs/ps110.json — подстанция 110/10 кВ, двухтрансформаторная.
//
// Зачем: в музее уже есть ТЭЦ (где электричество делают), КТП во дворе
// (где 10 кВ становятся 380/220) и ВРУ дома. Между ТЭЦ и двором — провал в
// целый уровень напряжения: город питается не от станции напрямую, а от
// понижающих подстанций. Отсюда и разный масштаб аварий: перегорел
// предохранитель в КТП — без света двор; отключилась ПС — без света район,
// и именно поэтому здесь всё задвоено: две линии, два трансформатора,
// секционированные шины.
//
// Схема — «мостик»: две воздушные линии 110 кВ заходят на линейные порталы,
// каждая через свой выключатель идёт на свой трансформатор, а между
// присоединениями стоит перемычка с выключателем — ею и переключают питание,
// когда одну линию выводят в ремонт.
//
// Система координат: X — поперёк (Т1 слева, Т2 справа), Y — высота,
// Z — вдоль присоединений: +Z (север) — линии и ОРУ-110, −Z — ЗРУ-10 кВ и ОПУ.
//
//   node tools/gen-ps110.js && node build.js --config configs/ps110.json --check
