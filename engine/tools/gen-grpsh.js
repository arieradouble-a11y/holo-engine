// в квартал. Двенадцатый объект категории «Электроника и оборудование».
//
// Почему он: единственный объект лайн-апа, где ошибка стоит не денег, а дома.
// Всё устройство ГРПШ подчинено одной мысли: давление за регулятором НИКОГДА не
// должно уйти вверх. Поэтому здесь три независимых рубежа — регулятор, который
// держит выходное давление; ПЗК, который отсекает газ при отказе регулятора; и
// ПСК, который стравит газ в свечу раньше, чем сработает ПЗК. Стенд показывает,
// почему их три и почему байпас в ГРПШ — не «удобная перемычка», а линия, которой
// работают вручную и под наблюдением.
//
// Система координат: X — вдоль газопровода (вход слева, выход справа), Y — высота
// от земли, Z — глубина (двери в +Z). Габарит ~2.2 × 2.0 × 0.7 м.
//
//   node tools/gen-grpsh.js && node build.js --config configs/grpsh.json
