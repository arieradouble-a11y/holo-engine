// Система координат: X — вдоль трубопровода, Y — высота от пола, Z — ширина.
// Габарит стенда ~1.3 × 1.4 × 0.4 м. Размеры по DN50 PN16.
//
//   node tools/gen-reg-klapan.js && node build.js --config configs/reg-klapan.json
