// Генератор configs/reg-klapan.json — регулирующий клапан DN 50 с электроприводом,
// учебный крупный план. Одиннадцатый объект категории «Электроника и оборудование».
//
// Почему отдельным стендом, если клапан уже есть в ИТП: там он размером с кулак и
// виден снаружи как «корпус с моторчиком». Здесь показано то, из-за чего он
// работает или НЕ работает: форма плунжера задаёт характеристику регулирования,
// а сам клапан управляем ровно настолько, насколько на нём падает давление
// (авторитет). Плохо подобранный клапан не «регулирует чуть хуже» — он ведёт себя
// как обычный кран: до 20 % хода ничего не меняется, потом всё открывается разом.
