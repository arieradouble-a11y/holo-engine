// четырёх.
//
// Компоновка «две линии»: первая идёт с запада на восток (скважины → сборный
// водовод → приёмная камера → аэрация и дегазация → фильтровальный зал), вторая
// разворачивается на север и идёт обратно (отстойники промывных вод →
// электролизная → резервуары чистой воды → НС-II → водоводы в Тюмень).
//
// Система координат: X — вдоль первой линии (запад −X — скважины), Y — высота от
// планировочной отметки 0 (минус — под землю), Z — поперёк площадки (вторая
