const guide = (x, z, y0, y1, dir, mat) => {
  const len = y1 - y0, yc = (y0 + y1) / 2, s = dir === 'x' ? 1 : 0;
  return [
    s ? { box: [0.016, len, 0.10, x, yc, z, mat] } : { box: [0.10, len, 0.016, x, yc, z, mat] },
    s ? { box: [0.062, len, 0.016, x + 0.039, yc, z, mat] }
      : { box: [0.016, len, 0.062, x, yc, z + 0.039, mat] },
    ...BRK.map(y => ({
      box: s ? [0.030, 0.10, 0.14, x - 0.023, y, z, mat]
             : [0.14, 0.10, 0.030, x, y, z - 0.023, mat] })),
  ];
};

