// Конвейер в вертикальной плоскости XY: полотно, рама, барабаны, приводная и
// натяжная станции, ограждение и трос аварийного останова вдоль ленты.
// Стойки обязательны — без них лента висит в воздухе, и floaters это ловит.
const lenta = (a, b, w, mat) => {
  const dx = b[0] - a[0], dy = b[1] - a[1];
  const L = Math.hypot(dx, dy), ang = Math.atan2(dy, dx) * 180 / Math.PI;
  const cx = (a[0] + b[0]) / 2, cy = (a[1] + b[1]) / 2, z = a[2];
  const out = [
    { box: [L, 0.10, w, cx, cy, z, mat + '-belt'], rot: [0, 0, ang] },
    { box: [L, 0.34, w + 0.16, cx, cy - 0.26, z, mat], rot: [0, 0, ang] },
    { cyl: [w * 0.22, w, a[0], a[1], z, mat, 'z', 12] },                          // натяжной барабан
    { cyl: [w * 0.22, w, b[0], b[1], z, mat, 'z', 12] },                          // приводной барабан
    { box: [0.7, 0.5, 0.5, b[0] + 0.4, b[1] - 0.1, z + w * 0.6, mat] },           // мотор-редуктор
    { cyl: [0.16, 0.4, b[0] + 0.85, b[1] - 0.1, z + w * 0.6, mat, 'x', 12] },
    { box: [0.5, 0.4, 0.4, a[0] - 0.35, a[1], z, mat] },                          // натяжная станция
  ];
  [0.22, 0.5, 0.78].forEach(t => {
    const x = a[0] + dx * t, y = a[1] + dy * t - 0.44;
    out.push({ box: [0.18, y, 0.18, x, y / 2, z, mat] });                          // стойка до пола
  });
  [-1, 1].forEach(s => {                                                           // ограждение и трос
    out.push({ box: [L, 0.06, 0.05, cx, cy + 0.42, z + s * (w / 2 + 0.16), mat], rot: [0, 0, ang] });
    out.push({ box: [L, 0.05, 0.04, cx, cy + 0.16, z + s * (w / 2 + 0.16), mat + '-lamp'], rot: [0, 0, ang] });
  });
  return out;
};

// Наклонный лоток/конвейер в плоскости ZY (поперёк площадки)
const lentaZ = (a, b, w, mat) => {
  const dz = b[2] - a[2], dy = b[1] - a[1];
  const L = Math.hypot(dz, dy), ang = -Math.atan2(dy, dz) * 180 / Math.PI;
  const cz = (a[2] + b[2]) / 2, cy = (a[1] + b[1]) / 2, x = a[0];
  return [
    { box: [w, 0.10, L, x, cy, cz, mat + '-belt'], rot: [ang, 0, 0] },
    { box: [w + 0.16, 0.34, L, x, cy - 0.26, cz, mat], rot: [ang, 0, 0] },
    ...[0.3, 0.7].map(t => {
      const z = a[2] + dz * t, y = a[1] + dy * t - 0.44;
      return { box: [0.18, y, 0.18, x, y / 2, z, mat] };
    }),
  ];
};

// Ограждение по периметру: столбы с шагом и два пояса сетки
const zabor = (x0, x1, z0, z1, mat, step) => {
  const out = [], st = step || 8;
  for (let x = x0; x <= x1 + 0.1; x += st) [z0, z1].forEach(z => {
    out.push({ box: [0.16, 2.4, 0.16, x, 1.2, z, mat] }); });
  for (let z = z0; z <= z1 + 0.1; z += st) [x0, x1].forEach(x => {
    out.push({ box: [0.16, 2.4, 0.16, x, 1.2, z, mat] }); });
  [z0, z1].forEach(z => [0.7, 1.9].forEach(y => out.push(
    { box: [x1 - x0, 0.06, 0.05, (x0 + x1) / 2, y, z, mat] })));
  [x0, x1].forEach(x => [0.7, 1.9].forEach(y => out.push(
    { box: [0.05, 0.06, z1 - z0, x, y, (z0 + z1) / 2, mat] })));
  return out;
};

