// Генератор configs/zhk.json — монолитный жилой комплекс с крышной котельной.
//
//   node tools/gen-zhk.js && node build.js --config configs/zhk.json --check
//
// Зачем: в музее были дома одной эпохи — панельные и кирпичные, пять и девять
// этажей, все на городских сетях. Современная высотка устроена принципиально
// иначе, и не «этажей больше», а по трём причинам, каждая из которых тянет за
// собой отдельные системы:
//
//  1. ВЫСОТА. Давления городского водопровода хватает этажей на двенадцать,
//     поэтому воду в доме поднимают своими насосами и делят на зоны: нижняя
//     живёт от одной группы, верхняя — от другой. Отсюда же пожарный водопровод
//     со своей насосной и незадымляемые лестницы.
//  2. СВОЙ ИСТОЧНИК ТЕПЛА. Когда мощности городской теплосети в квартале уже
//     разобраны, дом получает котельную на кровле — и вместе с ней газовый
//     стояк во всю высоту фасада. Что внутри той коробки на крыше, показывает
//     отдельный объект музея «Крышная котельная».
//  3. ПОДЗЕМНЫЙ ПАРКИНГ. Он не «место для машин», а этаж со своими системами:
//     дымоудаление, спринклеры, дренаж, уклоны к трапам.
//
// Система координат: X — длина дома, Y — высота (0 = пол первого этажа),
// Z — глубина (лицевой фасад +Z, тыльный −Z; газ и котельная на тыльной стороне).
