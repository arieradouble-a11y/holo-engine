// Генератор configs/osk.json — очистные сооружения канализации (ОСК) города.
//
// Зачем этот объект: в музее была вода «туда» (два водозабора, ВНС, ЦТП, дом)
// и не было воды «обратно». Цепочка обрывалась на КНС — куда стоки деваются
// дальше, витрина не показывала вовсе. Здесь она закрывается: приёмная камера →
// решётки → песколовки → первичные отстойники → аэротенки → вторичные
// отстойники → УФ → выпуск в реку, и параллельно вторая линия — обработка
// осадка, о которой обычно вообще не думают, а она половина станции.
//
// Компоновка «каре», как у водозаборов: первая линия идёт с запада на восток
// (механическая очистка), вторая разворачивается на север (биология), третья —
// осадок, на западе. Прямая линия на 200 м дала бы «блин»: станция очистки и
// так плоская, вертикали здесь всего три — цех обезвоживания, бункер кека на
// эстакаде и мачты освещения, поэтому подводящий коллектор и приёмная камера
// уходят глубоко вниз (стоки приходят самотёком с глубины), а вместе с ними
// растёт высота модели.
//
// Открытые сооружения показаны С ВОДОЙ (материал -water у зеркал песколовок,
// отстойников и аэротенков): это и есть половина узнаваемости объекта.
//
// Система координат: X — вдоль первой линии (запад −X — приём стоков),
// Y — высота от планировочной отметки 0, Z — поперёк площадки (биология и
// осадок на севере, +Z).
//
// Фактура (открытые источники, август 2026): единственные ОСК города, первая
// очередь 1973, вторая 2004; 220 тыс. м³/сут сейчас и 260 после реконструкции;
// концессия с конца 2017, работы с 2018, третий блок биологической очистки
// пущен в 2025; состав — решётки, песколовки, первичные отстойники, аэротенки,
// вторичные отстойники, насосная станция сырого осадка, цех механического
// обезвоживания; УФ-обеззараживание перед сбросом в реку; иловые площадки
// как резервная линия обезвоживания.
//
//   node tools/gen-osk.js && node build.js --config configs/osk.json --check
