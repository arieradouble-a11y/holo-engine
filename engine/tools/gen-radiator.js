// системы: стояк, замыкающий участок, радиатор, терморегулятор с термоголовкой,
// балансировочный клапан и распределитель тепла.
// Десятый объект категории «Электроника и оборудование».
//
// Почему он: это единственный узел ЖКХ, до которого житель дотягивается рукой, и
// потому самый переделываемый — и самый неправильно переделываемый. Стенд отвечает
// на то, из-за чего в доме потом холодно у соседей: зачем нужен замыкающий участок
// и почему вместо него нельзя ставить обычный кран; почему термоголовка меряет
// ВОЗДУХ, а не трубу; и почему распределитель тепла — не счётчик Гкал, а прибор,
// делящий общий домовой расход между квартирами.
//
// Система координат: X — вдоль стены (стояк слева), Y — высота от пола комнаты,
// Z — глубина (стена сзади, на −Z: камеры стенда смотрят с +Z). Габарит ~1.9 × 2.5 × 0.4 м.
//
//   node tools/gen-radiator.js && node build.js --config configs/radiator.json
