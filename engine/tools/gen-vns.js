// ---- bbox (повторяет extents хелперов box/cyl/frustum движка) ----------------
let min = [Infinity, Infinity, Infinity], max = [-Infinity, -Infinity, -Infinity];
function extend(c, d){ for (let i = 0; i < 3; i++){ min[i] = Math.min(min[i], c[i] - d[i]); max[i] = Math.max(max[i], c[i] + d[i]); } }
function walk(items, ox, oy, oz){
  items.forEach(it => {
    if (Array.isArray(it.items)){
      const at = it.at || [0,0,0], n = it.repeat || 1, st = it.step || [0,0,0];
      for (let i = 0; i < n; i++) walk(it.items, ox + at[0] + st[0]*i, oy + at[1] + st[1]*i, oz + at[2] + st[2]*i);
      return;
    }
    if (it.box){ const a = it.box; extend([ox+a[3], oy+a[4], oz+a[5]], [a[0]/2, a[1]/2, a[2]/2]); }
    else if (it.cyl){ const a = it.cyl, r = a[0], h = a[1], ax = a[6] || 'y';
      const d = ax === 'x' ? [h/2, r, r] : ax === 'z' ? [r, r, h/2] : [r, h/2, r];
      extend([ox+a[2], oy+a[3], oz+a[4]], d); }
    else if (it.frustum){ const a = it.frustum, R = Math.max(a[0], a[1]);
      extend([ox+a[3], oy+a[4], oz+a[5]], [R, a[2]/2, R]); }
  });
}
