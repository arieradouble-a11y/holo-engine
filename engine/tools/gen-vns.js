// Затвор с редуктором и маховиком (6 примитивов вместо 9 у kit'овой zadvizhka:
// на ВНС их четырнадцать штук, и разница в три примитива на узел — это 40 лишних).
const zatvor = (x, y, z, r, mat, ax) => {
  const a = ax || 'x';
  const dx = a === 'x' ? 1 : 0, dy = a === 'y' ? 1 : 0, dz = a === 'z' ? 1 : 0;
  const o = r * 1.20;
  const out = [
    { cyl: [r * 1.55, r * 1.35, x, y, z, mat, a, 16] },                        // корпус
    ...flanec(x - dx * o, y - dy * o, z - dz * o, r, mat, a),
    ...flanec(x + dx * o, y + dy * o, z + dz * o, r, mat, a),
  ];
  if (a === 'y') {                    // на вертикальной трубе маховик выносится вбок
    out.push({ cyl: [r * 0.22, r * 1.7, x + r * 1.7, y, z, mat, 'x', 8] },
             { box: [r * 1.1, r * 1.0, r * 1.2, x + r * 2.7, y, z, mat] },
             { torus: [r * 1.5, r * 0.16, x + r * 3.5, y, z, mat, 'x'] });
  } else {
    out.push({ cyl: [r * 0.22, r * 1.7, x, y + r * 2.0, z, mat, 'y', 8] },     // шток
             { box: [r * 1.1, r * 1.0, r * 1.2, x, y + r * 3.0, z, mat] },     // редуктор
             { torus: [r * 1.5, r * 0.16, x, y + r * 3.8, z, mat, 'y'] });     // маховик
  }
  return out;
};

