// «Словарь жилого дома» — то же, чем plant-kit.js стал для станций.
//
// Зачем: у любого МКД под отметкой 0 повторяется одно и то же — коробка
// технического подполья, ввод холодной воды с общедомовым счётчиком,
// канализационные лежаки с выпусками в дворовые колодцы, ВРУ. Различаются дома
// ВЫШЕ этой отметки (этажность, кровля, лифт) и тем, ЧТО стоит между вводом и
// стояками: элеватор в хрущёвке, насосная группа в высотке, вообще ничего в
// доме с крышной котельной. Общая часть живёт здесь, особенная — в генераторе
// конкретной серии.
//
// Система координат домов: X — длина дома, Y — высота (0 = пол первого этажа,
// подвал в минусе), Z — глубина (лицевой фасад +Z, тыльный −Z).
//
// Все функции возвращают массив элементов декларативного DSL (см. plant-kit).
// ⚠ Первой в подвале строится КОРОБКА: линтер floaters.mjs ищет детали, ни с чем
//   не соприкасающиеся, и труба без стены, к которой она приходит, честно
//   всплывает висящей.
'use strict';

const P = require('./plant-kit');
const { pipe, flanec, zadvizhka, obratnyi, manometr, shkaf, svet } = P;

// ── коробка технического подполья ────────────────────────────────────────────
// Плита, пол, стены, перекрытие, межсекционные стены с проходами, столбы под
// несущими, дренажный приямок с насосом и светильники. Высота подполья задаётся
// отметками: у хрущёвки оно низкое (1.9 м), у высотки — полноценный этаж.
function podval(o) {
  const { W, D, sections, sw, yFloor, yCeil } = o;
  const mat = o.mat || 'podval', dark = mat + '-dark';
  const zRis = o.zRis != null ? o.zRis : -D * 0.16;
  const hi = yCeil - yFloor;                       // чистая высота подполья
  const g = [
    { box: [W + 0.9, 0.35, D + 0.9, 0, yFloor - 0.32, 0, dark] },              // фундаментная плита
    { box: [W, 0.14, D, 0, yFloor - 0.07, 0, mat] },                           // бетонный пол
    { box: [W + 0.8, hi + 0.25, 0.4, 0, (yFloor + yCeil) / 2, -D / 2 - 0.2, mat] },   // стены подвала
    { box: [W + 0.8, hi + 0.25, 0.4, 0, (yFloor + yCeil) / 2, D / 2 + 0.2, mat] },
    { box: [0.4, hi + 0.25, D + 0.8, -W / 2 - 0.2, (yFloor + yCeil) / 2, 0, mat] },
    { box: [0.4, hi + 0.25, D + 0.8, W / 2 + 0.2, (yFloor + yCeil) / 2, 0, mat] },
    { box: [W + 0.4, 0.3, D + 0.4, 0, yCeil - 0.15, 0, mat] },                 // перекрытие над подвалом
  ];
  for (let s = 1; s < sections; s++) {                                         // межсекционные стены с проходами
    const px = -W / 2 + s * sw, ph = Math.min(2.0, hi - 0.2);
    g.push({ box: [0.3, hi, D, px, (yFloor + yCeil) / 2, 0, mat] });
    g.push({ box: [0.34, ph, 0.9, px, yFloor + ph / 2, zRis - 1.6, dark] });
  }
  for (let x = -W / 2 + sw / 2; x < W / 2; x += sw / 2)                        // столбы под несущими стенами
    g.push({ box: [0.34, hi, 0.34, x, (yFloor + yCeil) / 2, D * 0.22, mat] });
  if (o.pit !== false) {                                                       // приямок с дренажным насосом
    const px = o.pitX != null ? o.pitX : -W / 2 + 3.4, pz = o.pitZ != null ? o.pitZ : D * 0.30;
    const nh = Math.min(1.9, hi - 0.3);
    g.push({ box: [1.2, 0.5, 1.2, px, yFloor - 0.2, pz, dark] },
      { cyl: [0.11, 0.42, px, yFloor - 0.1, pz, o.pumpMat || 'vru', 'y', 12] },
      { cyl: [0.035, nh, px, yFloor + nh / 2, pz, o.pumpMat || 'vru', 'y', 8] });
  }
  for (let x = -W / 2 + sw / 2; x <= W / 2; x += sw)                           // светильники под перекрытием
    g.push(...svet(x, yCeil - 0.32, zRis + 1.4, mat));
  return g;
}

// ── ввод холодной воды с общедомовым узлом учёта ─────────────────────────────
// Гильза в стене, задвижка на границе ответственности, фильтр, счётчик с
// прямыми участками и опломбированной обводной, обратный клапан, манометры.
// Обводная нужна не «на всякий случай»: на время поверки счётчика воду не
// отключают, а пускают мимо него — и пломба показывает, что мимо не пускали.
function vvodVody(o) {
  const { x, y, z, r } = o, mat = o.mat || 'hvs', xW = o.xWall;
  return [
    { cyl: [r * 3.2, 0.6, xW + 0.25, y, z, mat, 'x', 14] },                    // гильза в стене
    ...pipe([[xW, y, z], [x + 3.4, y, z]], r, mat),
    ...zadvizhka(xW + 1.45, y, z, r, mat, 'x'),
    { cyl: [r * 1.7, 0.30, x - 1.2, y, z, mat, 'x', 14] },                     // сетчатый фильтр
    { frustum: [r * 0.9, r * 1.7, 0.24, x - 1.2, y - 0.18, z, mat] },
    { cyl: [r * 1.5, 0.36, x, y, z, mat, 'x', 16] },                           // счётчик ОДПУ
    { box: [0.13, 0.11, 0.14, x, y + 0.11, z, mat + '-dark'] },              // счётный механизм
    { box: [0.09, 0.055, 0.012, x, y + 0.13, z + 0.08, mat + '-lamp'] },      // табло
    { cyl: [0.022, 0.05, x + 0.12, y + 0.06, z, mat + '-lamp', 'y', 8] },     // пломба
    ...flanec(x - 0.18, y, z, r, mat, 'x'), ...flanec(x + 0.18, y, z, r, mat, 'x'),
    ...obratnyi(x + 0.9, y, z, r, mat, 'x'),
    ...manometr(x - 1.7, y + r, z, mat), ...manometr(x + 1.5, y + r, z, mat),
    ...pipe([[x - 1.7, y, z], [x - 1.7, y + 0.42, z], [x + 1.5, y + 0.42, z], [x + 1.5, y, z]], r * 0.8, mat),
    ...zadvizhka(x - 0.1, y + 0.42, z, r * 0.8, mat, 'x'),                     // опломбированная обводная
  ];
}

// ── канализация: лежак с ревизиями, выпуски в дворовые колодцы ───────────────
// Колодец выводится ЛЮКОМ НА ОТМЕТКУ ЗЕМЛИ: иначе он читается бочкой, висящей
// сбоку от дома, а не колодцем во дворе.
function kanalizaciya(o) {
  const { W, D, sections, sw, yFloor, yK, zKan } = o;
  const rKan = o.rKan || 0.055, rOut = o.rOut || 0.080, mat = o.mat || 'kanal';
  const g = [...pipe([[-W / 2 + 1.0, yK, zKan], [W / 2 - 1.0, yK, zKan]], rKan, mat)];
  for (let s = 0; s < sections; s++) {
    const cx = -W / 2 + (s + 0.5) * sw;
    g.push({ cyl: [rKan * 1.6, 0.18, cx, yK, zKan, mat + '-dark', 'x', 14] },  // ревизия на лежаке
      { box: [0.28, 0.05, 0.22, cx, yK - rKan - 0.03, zKan, mat] },            // опора лежака
      { box: [0.08, yK - rKan - yFloor, 0.08, cx, (yFloor + yK) / 2, zKan, mat] });
    g.push(...pipe([[cx, yK, zKan], [cx, yK - 0.25, zKan], [cx, yK - 0.25, D / 2 + 1.1]], rOut, mat));
    g.push({ cyl: [rOut * 2.6, 0.6, cx, yK - 0.25, D / 2 + 0.2, mat, 'z', 14] });   // гильза в стене
    g.push({ cyl: [0.62, Math.abs(yK - 0.9) + 0.05, cx, (yK - 0.9 - 0.05) / 2, D / 2 + 1.5, mat, 'y', 16] },
      { cyl: [0.70, 0.12, cx, -0.06, D / 2 + 1.5, mat + '-dark', 'y', 16] },   // горловина
      { cyl: [0.34, 0.07, cx, 0.03, D / 2 + 1.5, mat + '-dark', 'y', 14] });   // люк
  }
  return g;
}

// ── ВРУ: ввод кабеля, вводной шкаф со счётчиком, кабельные лотки ─────────────
function vru(o) {
  const { x, z, yFloor, yCeil, W, zRis } = o, mat = o.mat || 'vru';
  const h = Math.min(1.9, yCeil - yFloor - 0.45);
  return [
    ...shkaf(x, yFloor, z, mat, { w: 1.0, h, d: 0.34, doors: 2, floor: yFloor }),
    { box: [0.6, 0.5, 0.28, x + 0.9, yFloor + h * 0.58, z, mat] },             // шкаф учёта
    { box: [0.3, 0.16, 0.014, x + 0.9, yFloor + h * 0.62, z + 0.15, mat + '-lamp'] },
    { cyl: [0.09, 0.7, -W / 2 - 0.5, yFloor + 0.6, z, mat, 'x', 12] },         // гильза ввода кабеля
    { tube: [0.028, [[-W / 2 - 0.7, yFloor + 0.6, z], [-W / 2 + 0.4, yFloor + 0.55, z],
      [x - 0.45, yFloor + 0.5, z]], mat, 10] },                                // кабель ввода
    { box: [W - 2.2, 0.06, 0.22, 0.4, yCeil - 0.35, z, mat + '-dark'] },       // магистральный лоток
    { box: [0.22, 0.06, Math.abs(z - (zRis + 0.9)), x + 1.6, yCeil - 0.35, (z + zRis + 0.9) / 2, mat + '-dark'] },
    { box: [0.08, yCeil - 0.35 - (yFloor + h), 0.08, x + 0.5, (yCeil - 0.35 + yFloor + h) / 2, z, mat] },
  ];
}

// ── подвес магистрали к перекрытию ──────────────────────────────────────────
// Труба, идущая вдоль подвала, обязана на чём-то висеть: хомут на шпильке к
// перекрытию. Это ещё и ответ на вопрос «почему магистраль гудит» — жёсткий
// подвес передаёт вибрацию в плиту, и её слышно на первом этаже.
function podves(x, yPipe, z, yCeil, r, mat) {
  return [
    { box: [0.06, yCeil - 0.3 - yPipe, 0.06, x, (yCeil - 0.3 + yPipe) / 2, z, mat] },
    { box: [0.34, 0.05, 0.06, x, yPipe - r - 0.03, z, mat] },
  ];
}

module.exports = { podval, vvodVody, kanalizaciya, vru, podves };
