// жёсткая трубная трасса: прямые по осям + сферы-отводы (как в gen-itp.js)
const pipe = (pts, r, mat) => {
  const out = [];
  for (let i = 0; i + 1 < pts.length; i++) {
    const a = pts[i], b = pts[i + 1];
    const d = [b[0] - a[0], b[1] - a[1], b[2] - a[2]];
    const ax = d[0] ? 'x' : d[1] ? 'y' : 'z', len = Math.abs(d[0] || d[1] || d[2]);
    if (len < 1e-6) continue;
    out.push({ cyl: [r, len, (a[0]+b[0])/2, (a[1]+b[1])/2, (a[2]+b[2])/2, mat, ax, 12] });
    if (i > 0) out.push({ sphere: [r * 1.14, a[0], a[1], a[2], mat, 10] });
  }
  return out;
};

// фланец с кольцом болтов (гидрант, подставка, колонка — всё на фланцах)
const flanec = (y, r, n, mat, rBolt) => [
  { cyl: [r, 0.026, 0, y, 0, mat, 'y', 22] },
  { at: [0, y, 0], rstep: [0, 360 / n, 0], repeat: n, items: [
    { cyl: [0.009, 0.055, rBolt, 0, 0, mat, 'y', 6] },
  ]},
];

// соединительная головка ГМ-80: обод с двумя клыками — по ней рукав и цепляют
const golovka = (x, y, z, ax, mat) => {
  const dx = ax === 'x' ? 0.03 : 0, dz = ax === 'z' ? 0.03 : 0;
  const kl = ax === 'x' ? [0.018, 0.030, 0.026] : [0.026, 0.030, 0.018];   // клык поперёк оси
  return [
    { cyl: [0.058, 0.05, x, y, z, mat, ax, 16] },                          // обод головки
    { cyl: [0.066, 0.018, x + dx, y, z + dz, mat, ax, 16] },               // бурт под захват
    { box: [...kl, x + dx, y + 0.056, z + dz, mat] },                      // клык верхний
    { box: [...kl, x + dx, y - 0.056, z + dz, mat] },                      // клык нижний
  ];
};

