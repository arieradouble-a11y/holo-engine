// ---- локальные узлы, которых нет в plant-kit ---------------------------------
// Лёгкая площадка обслуживания: настил, бортик, поручень на стойках с одной
// стороны. Полноценная ploshchadka() кита стоит вдвое дороже, а на объекте 70 м
// её второе ограждение всё равно не читается.
function nastil(x, y, z, w, d, mat, opt) {
  const o = opt || {}, s = o.side != null ? o.side : 1, n = o.n || Math.max(2, Math.round(w / 3));
  return [
    { box: [w, 0.1, d, x, y, z, mat] },
    { box: [w, 0.16, 0.05, x, y + 0.08, z + s * d / 2, mat] },                 // бортик
    { at: [x - w / 2 + 0.15, y + 0.6, z + s * d / 2], repeat: n, step: [(w - 0.3) / (n - 1), 0, 0], items: [
      { box: [0.07, 1.1, 0.07, 0, 0, 0, mat] },                                // стойка ограждения
    ]},
    { box: [w, 0.07, 0.07, x, y + 1.15, z + s * d / 2, mat] },                 // поручень
  ];
}

// Маршевая лестница крупным шагом (подъём вдоль +X). Ступени намеренно реже
// натурных: на объекте 70 м натурный шаг 190 мм сливается в сплошную полосу.
function marsh(x, y0, z, h, run, mat, opt) {
  const o = opt || {}, n = o.n || 8, w = o.w || 1.1;
  const dx = run / n, dy = h / n, ang = Math.atan2(h, run) * 180 / Math.PI, L = Math.hypot(run, h);
  return [
    { at: [x + dx / 2, y0 + dy, z], repeat: n, step: [dx, dy, 0], items: [
      { box: [dx * 0.96, 0.06, w, 0, 0, 0, mat] },                             // ступень
    ]},
    { box: [L, 0.26, 0.07, x + run / 2, y0 + h / 2, z - w / 2, mat], rot: [0, 0, ang] },
    { box: [L, 0.26, 0.07, x + run / 2, y0 + h / 2, z + w / 2, mat], rot: [0, 0, ang] },
    { box: [L, 0.07, 0.07, x + run / 2, y0 + h / 2 + 1.05, z - w / 2, mat], rot: [0, 0, ang] },
    { box: [L, 0.07, 0.07, x + run / 2, y0 + h / 2 + 1.05, z + w / 2, mat], rot: [0, 0, ang] },
  ];
}

// Вертикальная стремянка с дугами ограждения (труба, градирня, этажерка).
function stremyanka(x, y0, z, h, mat, opt) {
  const o = opt || {}, ns = o.ns || Math.max(4, Math.round(h / 2.2)), na = o.na || Math.max(2, Math.round(h / 7));
  return [
    { box: [0.06, h, 0.06, x, y0 + h / 2, z - 0.26, mat] },
    { box: [0.06, h, 0.06, x, y0 + h / 2, z + 0.26, mat] },
    { at: [x, y0 + 0.6, z], repeat: ns, step: [0, (h - 1.0) / (ns - 1), 0], items: [
      { cyl: [0.024, 0.52, 0, 0, 0, mat, 'z', 6] },                            // ступень
    ]},
    { at: [x - 0.30, y0 + 2.4, z], repeat: na, step: [0, (h - 3.4) / Math.max(1, na - 1), 0], items: [
      // дуга — ГОРИЗОНТАЛЬНОЕ кольцо (нормаль Y), надетое на тетивы: с нормалью X
      // она висела в 0.33 м от стремянки (ловится floaters)
      { torus: [0.42, 0.026, 0, 0, 0, mat, 'y'] },
    ]},
  ];
}

// Опора трубопровода большого диаметра: стойка от планировки + ложемент.
function stoyka(x, y, z, r, mat, y0) {
  const b = y0 || 0;
  return [
    { box: [0.3, y - r - b, 0.3, x, (b + y - r) / 2, z, mat] },
    { box: [0.62, 0.14, r * 2.5, x, y - r - 0.07, z, mat] },
  ];
}

// Центробежная машина крупным планом (циркнасос, сетевой насос, дутьевой
// вентилятор, дымосос): улитка со спиралью, всас, напор, вал, мотор, рама.
function mashina(x, y, z, mat, opt) {
  const o = opt || {}, R = o.r || 1.2, L = o.len || 0.9, ax = o.ax || 'x';
  const s = ax === 'x' ? 1 : 0, t = ax === 'z' ? 1 : 0;      // направление вала
  const mR = o.mr || R * 0.52, mL = o.ml || R * 1.9;
  return [
    { box: [R * 2.6, 0.3, R * 2.6, x, y - R - 0.5, z, mat + '-dark'] },        // фундаментная рама
    { box: [R * 0.5, 0.35, R * 0.5, x, y - R - 0.18, z, mat + '-dark'] },      // стойка улитки
    { cyl: [R, L, x, y, z, mat, ax, 20] },                                     // улитка
    { torus: [R * 0.82, L * 0.55, x, y, z, mat, ax] },                         // спиральный отвод
    { cyl: [R * 0.58, L * 0.5, x - s * L * 0.75, y, z - t * L * 0.75, mat, ax, 16] },   // всасывающий карман
    { frustum: [R * 0.72, R * 0.58, L * 0.5, x - s * L * 1.25, y, z - t * L * 1.25, mat, ax] },
    { box: [R * 0.8, R * 1.5, R * 0.8, x, y + R * 1.15, z, mat] },             // напорный патрубок
    { cyl: [R * 0.13, R * 1.5, x + s * (L / 2 + R * 0.75), y, z + t * (L / 2 + R * 0.75), mat, ax, 10] },  // вал
    { box: [R * 0.55, R * 0.55, R * 0.55, x + s * (L / 2 + R * 0.5), y, z + t * (L / 2 + R * 0.5), mat + '-dark'] },  // подшипник
    { cyl: [mR, mL, x + s * (L / 2 + R * 1.5 + mL / 2), y, z + t * (L / 2 + R * 1.5 + mL / 2), mat, ax, 16] },        // двигатель
    { at: [x + s * (L / 2 + R * 1.5 + mL * 0.2), y, z + t * (L / 2 + R * 1.5 + mL * 0.2)], repeat: 5,
      step: [s * mL * 0.15, 0, t * mL * 0.15], items: [
      { torus: [mR * 1.06, mR * 0.06, 0, 0, 0, mat, ax] },                     // рёбра охлаждения
    ]},
    { box: [mL * 1.1, 0.4, mR * 2.2, x + s * (L / 2 + R * 1.5 + mL / 2), y - mR - 0.2, z + t * (L / 2 + R * 1.5 + mL / 2), mat + '-dark'] },  // лапы мотора
  ];
}

