// с крюком, которая не имеет ни кузова, ни пресса вообще.
//
// Как это работает: стрела с крюком заваливается назад, крюк цепляет петлю на
// передней раме бункера, гидроцилиндры тянут — бункер въезжает на надрамник по
// роликам, сам себя поднимая. Пустой ставится обратно тем же движением. Поэтому
// одна машина за смену меняет десяток бункеров, а на площадке всегда стоит
// пустой — если, конечно, регоператор довёз.
//
// Шасси и кабина — общие для всего парка: tools/lib/kamaz-6x4.js + донорская
// кабина КамАЗ (part00/part01 копируются из ../kdm-parts, см. README).
