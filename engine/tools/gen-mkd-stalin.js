// Генератор configs/mkd-stalin.json — кирпичный дом послевоенной постройки
// («сталинка»), 1949–1956 годов.
//
//   node tools/gen-mkd-stalin.js && node build.js --config configs/mkd-stalin.json --check
//
// Зачем: в музее собрались дома, построенные УЖЕ ПОД городские сети — пятиэтажка
// с элеватором, девятиэтажка со стояками, высотка со своей котельной. Этот дом
// старше самих сетей, и почти всё в нём — след того, чего в момент постройки не
// существовало:
//
//  • ГОРЯЧЕЙ ВОДЫ В ПРОЕКТЕ НЕ БЫЛО. В подвал заходит ОДНА труба воды, а горячую
//    делают в квартире газовые колонки. Поэтому «отключение ГВС» такому дому
//    ничего не говорит, зато остановка газа оставляет без горячей воды сразу всех.
//  • ВЕНТИЛЯЦИЯ — КИРПИЧНЫЕ КАНАЛЫ В СТЕНАХ, наследники печных дымоходов. В те же
//    стволы включены дымоотводы колонок, и именно поэтому опрокинутая тяга в
//    канале здесь не бытовое неудобство, а угроза отравления.
//  • ПЕРЕКРЫТИЯ ДЕРЕВЯННЫЕ, по балкам с накатом. От них — и ограничение нагрузки
//    на пол, и слышимость между этажами, и цена капремонта такого дома.
//  • ОТОПЛЕНИЕ ПРИШЛО ПОЗЖЕ: дом подключили к городской сети, когда она дошла до
//    квартала, поэтому узел с элеватором стоит в подвале как «пристроенный», а
//    разводка сделана по подвалу поверх старых конструкций.
//
// Система координат: X — длина дома, Y — высота (0 = пол первого этажа),
// Z — глубина (лицевой фасад +Z, тыльный −Z; газовый ввод на тыльном).
