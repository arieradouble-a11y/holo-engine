const W = B.sections * B.sectionWidth;      // 45
const D = B.depth, H = B.floors * B.floorHeight, HT = H + B.atticH;   // 16.5 / 18.5
const RISE = D * 0.30;

// ---- отметки и оси -----------------------------------------------------------
