const xWall = -W / 2 - 0.4;
const xIn = -W / 2 + 3.4;
const xEl = xIn + 3.8;
const zGaz = -D / 2 - 0.24;
const rHeat = 0.038, rHvs = 0.030, rGaz = 0.024;

const nR = B.risers.length;
const risX = s => -W / 2 + (B.risers.indexOf(s) + 1) * W / (nR + 1);
// оси дымовентиляционных стволов: по два на секцию — кухонный и санузловый
