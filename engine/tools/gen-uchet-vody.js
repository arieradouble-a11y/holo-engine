// Генератор configs/uchet-vody.json — общедомовой узел учёта холодной воды (ОДПУ)
// на вводе в жилой дом. Шестой объект категории «Электроника и оборудование».
//
// Почему он: по этому узлу дом платит за воду, и именно вокруг него больше всего
// бытовых мифов. Стенд отвечает на три вечных вопроса: зачем обводная линия, если
// она всё равно опломбирована; почему счётчик нельзя врезать вплотную к отводу;
// и что мешает воде «мотать счётчик назад».
//
// Система координат: X — вдоль узла (ввод из земли слева, в дом справа),
// Y — высота от пола подвала, Z — глубина (стена сзади). Габарит ~2.3 × 1.7 × 0.5 м.
//
//   node tools/gen-uchet-vody.js && node build.js --config configs/uchet-vody.json
