const zW = -0.30;                      // плоскость стены подвала (ЗА узлом от зрителя:
                                       // камеры стенда смотрят с +Z, и стена на +Z закрыла бы всё)
const zC = 0.02;                       // ось трубопроводов по глубине
const rP = 0.054;                      // наружный радиус трубы DN100 (108 мм)
const rM = 0.045;                      // радиус на измерительном участке DN80
const mX = -0.05;                      // центр счётчика
const dN = 0.08;                       // условный проход счётчика (для правила 5D/3D)

// жёсткая трубная трасса: прямые по осям + сферы-отводы
const pipe = (pts, r, mat) => {
  const out = [];
  for (let i = 0; i + 1 < pts.length; i++) {
    const a = pts[i], b = pts[i + 1];
    const d = [b[0] - a[0], b[1] - a[1], b[2] - a[2]];
    const ax = d[0] ? 'x' : d[1] ? 'y' : 'z', len = Math.abs(d[0] || d[1] || d[2]);
    if (len < 1e-6) continue;
    out.push({ cyl: [r, len, (a[0]+b[0])/2, (a[1]+b[1])/2, (a[2]+b[2])/2, mat, ax, 14] });
    if (i > 0) out.push({ sphere: [r * 1.14, a[0], a[1], a[2], mat, 10] });
  }
  return out;
};

// фланцевая пара с кольцом болтов на горизонтальной трубе
const flanec = (x, y, r, n, mat) => [
  { cyl: [r + 0.028, 0.022, x - 0.012, y, zC, mat, 'x', 20] },
  { cyl: [r + 0.028, 0.022, x + 0.012, y, zC, mat, 'x', 20] },
  { at: [x, y, zC], rstep: [360 / n, 0, 0], repeat: n, items: [
    { cyl: [0.007, 0.06, 0, r + 0.017, 0, mat, 'x', 6] },
  ]},
];

