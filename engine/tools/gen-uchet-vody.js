  ...(mark ? [
    { cyl: [0.012, 0.05, x + 0.03, y + r + 0.09, zC, mark, 'z', 8] },           // проушина под пломбу
    { torus: [0.020, 0.005, x + 0.03, y + r + 0.05, zC, mark, 'z'] },           // проволока пломбы
    { cyl: [0.016, 0.012, x + 0.03, y + r + 0.03, zC, mark, 'y', 10] },         // свинцовая пломба
  ] : []),
