const ang = (a, b) => -Math.atan2(b[0] - a[0], b[1] - a[1]) * 180 / Math.PI;
const len = (a, b) => Math.hypot(b[0] - a[0], b[1] - a[1]);
const mid = (a, b, t) => [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t];
const balka = (a, b, w, th, z, mat) => {
  const c = mid(a, b, 0.5);
  return [{ box: [th, len(a, b), w, c[0], c[1], z, mat], rot: [0, 0, ang(a, b)] },
    { cyl: [w * 0.45, th * 1.3, a[0], a[1], z, mat, 'z', 12] },
    { cyl: [w * 0.45, th * 1.3, b[0], b[1], z, mat, 'z', 12] }];
};
function cil(a, b, r, mat, z, part) {
  const L = len(a, b), A = ang(a, b), t = part == null ? 0.55 : part;
  const c1 = mid(a, b, t / 2), c2 = mid(a, b, 1 - (1 - t) / 2), j = mid(a, b, t);
  return [{ at: [0, 0, z], items: [
    { cyl: [r, L * t, c1[0], c1[1], 0, mat, 'y', 14], rot: [0, 0, A] },
    { cyl: [r * 0.52, L * (1 - t) + 0.06, c2[0], c2[1], 0, mat + '-dark', 'y', 12], rot: [0, 0, A] },
    { cyl: [r * 1.12, 0.06, j[0], j[1], 0, mat, 'y', 14], rot: [0, 0, A] },
    { torus: [r * 0.9, r * 0.26, a[0], a[1], 0, mat, 'z'] },
    { torus: [r * 0.6, r * 0.2, b[0], b[1], 0, mat + '-dark', 'z'] },
  ] }];
}

