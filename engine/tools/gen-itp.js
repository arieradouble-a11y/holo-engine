// теплообменника, а по дому идёт своя вода 95/70, которую гонит свой насос.
//
// Система координат: X — длина блока (ввод теплосети слева −X, дом справа +X),
// Y — высота от пола, Z — глубина (первичный контур сзади, вторичный спереди).
// Габарит блока ~3.0 × 1.9 × 0.9 м.
//
//   node tools/gen-itp.js && node build.js --config configs/itp.json
