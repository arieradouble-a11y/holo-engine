// ---- пластинчатый разборный теплообменник ------------------------------------
// Неподвижная плита + пакет гофрированных пластин + прижимная плита на стяжных
// шпильках. У одноходового ПТО ВСЕ ЧЕТЫРЕ присоединения на неподвижной плите —
// поэтому патрубки смотрят в одну сторону (−X), а вторичные трубы обходят пакет.
// Шаг пластин намеренно крупнее натурного: в контурном пассе пакет из четырёх
// десятков боксов сливается в светящийся «клубок» — у бокса рёбра 90°, их не
// прореживает никакой hotAngle. Полтора десятка пластин с видимым зазором
// читаются пакетом, а не пятном, и учебный смысл узла сохраняется.
const pto = (x0, z, y0, hgt, wid, n, mat) => {
  const yc = y0 + hgt / 2, st = 0.017, packLen = n * st;
  const xPress = x0 + 0.055 + packLen;
  const yHi = y0 + hgt * 0.78, yLo = y0 + hgt * 0.22, zOff = wid * 0.27;
  return [
    { box: [0.055, hgt, wid, x0, yc, z, mat] },                                 // неподвижная плита
    { at: [x0 + 0.05, yc, z], repeat: n, step: [st, 0, 0], items: [
      { box: [0.005, hgt - 0.07, wid - 0.05, 0, 0, 0, mat + '-plate'] },        // пластина пакета
    ]},
    { box: [0.045, hgt, wid, xPress, yc, z, mat] },                             // прижимная плита
    // стяжные шпильки по четырём углам: repeat по высоте × repeat по ширине
    { at: [(x0 + xPress) / 2, y0 + 0.05, z - wid / 2 + 0.045], repeat: 2, step: [0, hgt - 0.10, 0], items: [
      { at: [0, 0, 0], repeat: 2, step: [0, 0, wid - 0.09], items: [
        { cyl: [0.011, packLen + 0.16, 0, 0, 0, mat, 'x', 8] },                 // шпилька
      ]},
    ]},
    // четыре патрубка на неподвижной плите: первичка сзади, вторичка спереди
    ...[[yHi, zOff], [yLo, zOff], [yHi, -zOff], [yLo, -zOff]].map(([y, dz]) => (
      { cyl: [0.030, 0.11, x0 - 0.055, y, z + dz, mat, 'x', 14] })),
    ...[[yHi, zOff], [yLo, zOff], [yHi, -zOff], [yLo, -zOff]].map(([y, dz]) => (
      { cyl: [0.048, 0.022, x0 - 0.105, y, z + dz, mat, 'x', 14] })),           // ответный фланец
    { box: [0.07, y0 - fyT, wid * 0.8, x0, (y0 + fyT) / 2, z, mat] },           // опора под плитой
    { box: [0.07, y0 - fyT, wid * 0.8, xPress, (y0 + fyT) / 2, z, mat] },
    { box: [0.10, 0.02, 0.08, x0 + 0.02, y0 + hgt + 0.015, z, mat] },           // шильд с маркой
  ];
};

