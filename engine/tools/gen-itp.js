// Жёсткая трубная трасса: прямые участки по осям + сферы-отводы в коленах.
// Catmull-Rom (`tube`) хорош для кабеля и рукава, но трубопровод в тепловом
// пункте — это прямые и отводы 90°: «змейка» между узлами сразу читается
// шлангом и роняет весь стенд в игрушку (видно на PBR-рендере, не на голограмме).
// Соседние точки обязаны отличаться ровно по одной оси.
const pipe = (pts, r, mat) => {
  const out = [];
  for (let i = 0; i + 1 < pts.length; i++) {
    const a = pts[i], b = pts[i + 1];
    const d = [b[0] - a[0], b[1] - a[1], b[2] - a[2]];
    const ax = d[0] ? 'x' : d[1] ? 'y' : 'z', len = Math.abs(d[0] || d[1] || d[2]);
    if (len < 1e-6) continue;
    out.push({ cyl: [r, len, (a[0]+b[0])/2, (a[1]+b[1])/2, (a[2]+b[2])/2, mat, ax, 12] });
    if (i > 0) out.push({ sphere: [r * 1.14, a[0], a[1], a[2], mat, 10] });      // отвод
  }
  return out;
};

