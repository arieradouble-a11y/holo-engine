// Генератор configs/itp.json — индивидуальный тепловой пункт (ИТП) жилого дома,
// блочный, на общей раме. Третий объект категории «Электроника и оборудование».
//
// Почему он, а не ещё одна станция: ЦТП у нас уже есть ЗДАНИЕМ (configs/ctp.json),
// а ИТП — это шкафной блок в подвале каждого дома, и смотреть его надо вплотную.
