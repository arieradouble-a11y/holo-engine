// === К1 — смотровой колодец (kolodec) ==========================================
function shakhta(cx, yBot, yTop, mat) {
  const out = [];
  let y = yBot;
  while (y + 0.02 < yTop) {
    const h = Math.min(H_RING, yTop - y);
    out.push(...arc(cx, y + h / 2, 0, RW, h - 0.012, TW, mat));
    out.push(...kromka(cx, y + h / 2, 0, RW, h - 0.012, TW, mat, 2));
    out.push(...kromka(cx, y + h / 2, 0, RW, h - 0.012, TW, mat, 178));
    // ⚠ Стык колец — не декор: сероводород и корни заходят в сеть именно через
    // него, поэтому стык заделывают и он же первым течёт.
    out.push(...arc(cx, y + h, 0, RW + 0.012, 0.03, TW + 0.03, mat, { n: 9 }));
    y += H_RING;
  }
  return out;
}
