// Генератор configs/kolodec.json — канализационные колодцы в разрезе
// (смотровой + перепадной на врезке в городской коллектор).
//
// Зачем: водоотведение в музее было выстроено с обоих концов — сантехприбор и
// стояки внутри домов, КНС, очистные, выпуск в реку, — а РАБОЧЕЙ ТОЧКИ сети не
// было. При этом:
//   · именно в колодце проходит граница «дом — город»: до первого колодца за
//     отмосткой отвечает управляющая организация, дальше водоканал, и от этого
//     зависит, кому звонить, когда потекло;
//   · именно в колодце видно, почему при засоре топит ПОДВАЛ И ПЕРВЫЙ ЭТАЖ, а
//     не ту квартиру, где бросили тряпку: сток поднимается и уходит в самую
//     низкую точку слива;
//   · обе обслуживающие машины музея — илосос и каналопромывочная — работают
//     ровно сюда, но самой точки горожанин до сих пор не видел.
//
// Оси: X — вдоль дворовой сети, Y — глубина (0 = верх покрытия), Z — поперёк;
// городской коллектор проложен ВДОЛЬ Z, дворовая сеть врезается в него сверху.
//
// ⚠ РАССТОЯНИЕ МЕЖДУ КОЛОДЦАМИ СЖАТО: по нормам смотровые колодцы ставят не
// реже чем через 35-50 м, в модели между ними 5,6 м. Иначе объект длиной под
// сотню метров при глубине 5 вырождается в нитку (тот же приём, что со сжатым
// пролётом ВЛ и укороченной колонной скважины) — настоящее значение вынесено
// в характеристики и в подпись узла.
//
// ⚠ УКЛОН НЕ ПРЕУВЕЛИЧЕН. 0,007 на участке 5,6 м — это 3,9 см, и на модели его
// действительно не видно. Так и задумано: об этом говорит отдельный узел —
// уклон самотёчной сети проверяют нивелиром, а не на глаз.
//
//   node tools/gen-kolodec.js && node build.js --config configs/kolodec.json --check
