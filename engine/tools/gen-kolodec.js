// Отрезок произвольного направления (та же математика, что в gen-vl04):
// направление (0,1,0) под Rx·Ry·Rz при ry=0 даёт (−sin rz, cos rz·cos rx,
// cos rz·sin rx), отсюда rz = −asin(dx), rx = atan2(dz, dy).
const seg = (a, b, r, mat, s) => {
  const d = [b[0] - a[0], b[1] - a[1], b[2] - a[2]];
  const L = Math.hypot(d[0], d[1], d[2]);
  if (L < 1e-6) return [];
  const u = [d[0] / L, d[1] / L, d[2] / L];
  const rz = -Math.asin(Math.max(-1, Math.min(1, u[0]))) * R2D;
  const h = Math.hypot(u[1], u[2]);
  const rx = h < 1e-9 ? 0 : Math.atan2(u[2], u[1]) * R2D;
  return [{ cyl: [r, L, (a[0] + b[0]) / 2, (a[1] + b[1]) / 2, (a[2] + b[2]) / 2, mat, 'y', s || 10],
            rot: [+rx.toFixed(3), 0, +rz.toFixed(3)] }];
};

// ДУГА КОЛЬЦА, А НЕ КОЛЬЦО ЦЕЛИКОМ. Сплошная железобетонная камера в аддитивном
// каркасе — это «стеклянный ящик»: от неё видно только силуэт, а лоток, скобы и
// трубы внутри пропадают. Поэтому у каждого кольца вырезан сектор, обращённый к
// зрителю (+Z), и camera смотрит внутрь камеры, как в настоящий разрез.
// Стенка набирается хордами: группа с rstep по окружности — тот же приём, что у
// крыльев трактора и ворса щётки.
function arc(cx, cy, cz, r, h, wall, mat, opt) {
  const o = opt || {};
  // ⚠ ПО УМОЛЧАНИЮ ОСТАЁТСЯ ЗАДНЯЯ ПОЛОВИНА. Первая версия оставляла 280° и
  // вырезала лишь узкий сектор — камера всё равно читалась закрытой бочкой, а
  // плита покрытия сверху накрывала оба колодца целиком, и внутрь не было видно
  // ничего. Объект переведён в честный ПРОДОЛЬНЫЙ РАЗРЕЗ по оси сети: у камер,
  // люков, плит и оснований остаётся половина, у дорожной одежды — торец среза.
  // ⚠ ЗНАК Z ПРОВЕРЕН ЗАМЕРОМ, А НЕ ВЫВЕДЕН НА БУМАГЕ. Поворот группы вокруг Y
  // на угол θ уводит локальный +X в мировые (cos θ, 0, −sin θ), поэтому «задняя»
  // половина — это θ от 0 до 180, а не от 180 до 360, как кажется по привычной
  // тригонометрии. Первая версия оставляла ПЕРЕДНЮЮ стенку, и камера была
  // закрыта от зрителя ровно тем, что надо было срезать: на глаз это читалось
  // просто как «бочка», нашлось только подсчётом сегментов в дампе.
  const a0 = o.a0 != null ? o.a0 : 2;     // начало дуги, градусы
  const a1 = o.a1 != null ? o.a1 : 178;   // конец (через 90 = задняя стенка)
  // ⚠ ЧИСЛО ХОРД ДЕРЖИМ МАЛЫМ. Первая версия брала 22 сегмента на кольцо, и
  // стенка превращалась в частокол: каждая коробочка даёт четыре вертикальных
  // ребра, и в аддитивном каркасе 2,5-метровая камера читалась гребёнкой, а не
  // круглой стеной. Тот же класс, что плотная мелочь щётки трактора.
  const n = o.n || 10;
  const step = (a1 - a0) / n;
  // хорду считаем по СРЕДНЕЙ ЛИНИИ стенки, а не по внутреннему радиусу,
  // иначе на крупном шаге соседние сегменты расходятся углами
  const chord = 2 * (r + wall / 2) * Math.sin((step / 2) / R2D) * 1.05;
  return [{
    at: [cx, cy, cz], rot: [0, a0 + step / 2, 0], repeat: n, rstep: [0, step, 0],
    items: [{ box: [wall, h, chord, r + wall / 2, 0, 0, mat] }],
  }];
}

// ⚠ ПЛИТУ В РАЗРЕЗЕ РИСУЕМ ПЛАСТИНОЙ, А НЕ ВЕЕРОМ КЛИНЬЕВ. Первая версия
// набирала половину диска теми же хордами, что и стенку, — и на дне каждого
// колодца выросла «шестерёнка» из радиальных коробочек. Круглой плита всё равно
// не читается: в разрезе от неё видно торец, а торец — это прямоугольник.
function plita(cx, cy, cz, R, h, mat) {
  return [{ box: [2 * R, h, R, cx, cy, cz - R / 2, mat] }];
}
// Мелкие круглые детали на срезе (люк, опорное кольцо) — половина многоугольника:
// шести сегментов хватает, крупнее их всё равно не разглядеть.
function polu(cx, cy, cz, R, h, mat, n) {
  return arc(cx, cy, cz, 0, h, R, mat, { n: n || 6 });
}

// Кромка среза кольца: без неё разрез читается как «отломано», а не «разрезано».
function kromka(cx, cy, cz, r, h, wall, mat, ang) {
  const rad = ang / R2D;                       // знак Z — как у arc()
  return [{ box: [wall + 0.02, h, 0.03, cx + (r + wall / 2) * Math.cos(rad), cy,
                  cz - (r + wall / 2) * Math.sin(rad), mat], rot: [0, ang, 0] }];
}

// Лоток (кювета) по дну: открытый жёлоб в форме нижней половины трубы, по бокам
// полки с уклоном к нему. Стоять в колодце можно только на полках — сам лоток
// открыт, иначе сеть нечем прочистить.
function lotok(cx, cz, yLot, d, len, mat, axis) {
  const out = [], r = d / 2, n = 9;
  for (let i = 0; i < n; i++) {
    const a = Math.PI * (0.5 + (i + 0.5) / n);       // нижняя половина
    const x = Math.cos(a) * (r + 0.03), y = Math.sin(a) * (r + 0.03);
    const w = 2 * (r + 0.03) * Math.sin(Math.PI / (2 * n)) * 1.15;
    const c = axis === 'z'
      ? { box: [len, 0.035, w, cx, yLot + r + y, cz + x, mat] }
      : { box: [w, 0.035, len, cx + x, yLot + r + y, cz, mat] };
    c.rot = axis === 'z' ? [-(a * R2D - 90), 0, 0] : [0, 0, a * R2D - 90];
    out.push(c);
  }
  return out;
}

