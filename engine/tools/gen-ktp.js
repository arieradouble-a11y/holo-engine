// напряжение под дождём: путь тока по мокрой поверхности длиннее прямого.
const izo = (x, y, z, r, h, mat, ax, n) => {
  const k = n || 4, ax3 = ax || 'y';
  const step = ax3 === 'x' ? [h / (k + 1), 0, 0] : ax3 === 'z' ? [0, 0, h / (k + 1)] : [0, h / (k + 1), 0];
  return [
    { cyl: [r, h, x, y, z, mat, ax3, 12] },
    { at: [x - step[0] * (k - 1) / 2, y - step[1] * (k - 1) / 2, z - step[2] * (k - 1) / 2],
      repeat: k, step, items: [{ torus: [r * 1.5, r * 0.42, 0, 0, 0, mat, ax3] }] },
    { cyl: [r * 1.25, 0.018, x - (ax3 === 'x' ? h / 2 : 0), y - (ax3 === 'y' ? h / 2 : 0),
            z - (ax3 === 'z' ? h / 2 : 0), mat, ax3, 12] },
    { cyl: [r * 1.25, 0.018, x + (ax3 === 'x' ? h / 2 : 0), y + (ax3 === 'y' ? h / 2 : 0),
            z + (ax3 === 'z' ? h / 2 : 0), mat, ax3, 12] },
  ];
};

