// Шина: полоса 50×8 по ломаной из осевых отрезков. На стыках — болтовое
// соединение кубиком: без него сегменты расходятся на толщину полосы, и
// floaters.mjs честно ругается на «висящую» шину.
const shina = (pts, mat, w = 0.05, th = 0.008) => {
  const out = [];
  for (let i = 0; i + 1 < pts.length; i++) {
    const a = pts[i], b = pts[i + 1];
    const d = [b[0] - a[0], b[1] - a[1], b[2] - a[2]];
    const len = Math.abs(d[0] || d[1] || d[2]);
    if (len < 1e-6) continue;
    const ax = Math.abs(d[0]) > 1e-6 ? 'x' : Math.abs(d[1]) > 1e-6 ? 'y' : 'z';
    const c = [(a[0] + b[0]) / 2, (a[1] + b[1]) / 2, (a[2] + b[2]) / 2];
    const s = ax === 'x' ? [len, w, th] : ax === 'y' ? [th, len, w] : [w, th, len];
    out.push({ box: [s[0], s[1], s[2], c[0], c[1], c[2], mat] });
    if (i > 0) out.push({ box: [0.055, 0.055, 0.055, a[0], a[1], a[2], mat] });
  }
  return out;
};

