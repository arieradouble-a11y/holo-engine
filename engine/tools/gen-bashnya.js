// Ограждение зоны санитарной охраны: столбы, два пояса, ворота на +X
const zabor = (x0, x1, z0, z1, mat) => {
  const out = [], st = 6;
  for (let x = x0; x <= x1 + 0.1; x += st) [z0, z1].forEach(z =>
    out.push({ box: [0.14, 2.2, 0.14, x, 1.1, z, mat] }));
  for (let z = z0; z <= z1 + 0.1; z += st) [x0, x1].forEach(x =>
    out.push({ box: [0.14, 2.2, 0.14, x, 1.1, z, mat] }));
  [z0, z1].forEach(z => [0.6, 1.8].forEach(y =>
    out.push({ box: [x1 - x0, 0.05, 0.04, (x0 + x1) / 2, y, z, mat] })));
  [x0, x1].forEach(x => [0.6, 1.8].forEach(y =>
    out.push({ box: [0.04, 0.05, z1 - z0, x, y, (z0 + z1) / 2, mat] })));
  return out;
};

// Штриховка плоскости разреза: косые чёрточки, как на чертеже. Сплошной объём
// грунта в аддитивном каркасе читается стеклянным ящиком — на теплотрассе это
// уже проверено, поэтому грунт показан ПЛОСКОСТЬЮ, а не коробкой.
const shtrih = (x, y, z, w, h, mat, n) => {
  const k = n || 8, out = [{ box: [w, h, 0.06, x, y, z, mat] }];
  for (let i = 0; i < k; i++) out.push({
    box: [Math.min(w, h) * 0.7, 0.04, 0.04, x - w / 2 + (i + 0.5) * (w / k), y, z + 0.05, mat],
    rot: [0, 0, 45] });
  return out;
};

