// Оттяжка угловой опоры. Подкос здесь поставить НЕКУДА: равнодействующая
// тяжения двух пролётов тянет опору в сторону (−X, +Z), то есть на проезжую
// часть, а подкос работает на СЖАТИЕ и должен стоять именно с той стороны,
// куда клонит. Поэтому опору держат оттяжкой — стальным канатом на
// противоположной стороне, работающим на растяжение, с анкерной плитой в грунте.
function ottyazhka(x, z, dx, dz, mat) {
  const top = [x + dx * 0.14, 6.30, z + dz * 0.14];
  const gnd = [x + dx * 2.40, 0, z + dz * 2.40];
  const out = [
    { box: [0.22, 0.16, 0.22, top[0], top[1], top[2], mat] },                    // коуш на опоре
    ...seg(top, [x + dx * 1.10, 3.40, z + dz * 1.10], 0.011, mat, 6),            // верхняя ветвь каната
    { cyl: [0.05, 0.16, x + dx * 1.15, 3.25, z + dz * 1.15, mat, 'y', 10] },     // изолятор в разрыве
    { cyl: [0.075, 0.05, x + dx * 1.15, 3.32, z + dz * 1.15, mat, 'y', 10] },
    { cyl: [0.075, 0.05, x + dx * 1.15, 3.18, z + dz * 1.15, mat, 'y', 10] },
    ...seg([x + dx * 1.20, 3.10, z + dz * 1.20], [x + dx * 1.95, 1.05, z + dz * 1.95], 0.011, mat, 6),
    { cyl: [0.035, 0.34, x + dx * 2.02, 0.86, z + dz * 2.02, mat, 'y', 8],
      rot: [dz * 40, 0, -dx * 40] },                                             // талреп
    ...seg([x + dx * 2.10, 0.62, z + dz * 2.10], gnd, 0.014, mat, 6),
    // защитный кожух на нижней ветви: оттяжка пересекает тротуар на высоте роста
    { cyl: [0.055, 1.90, x + dx * 2.14, 0.86, z + dz * 2.14, mat, 'y', 8],
      rot: [dz * 40, 0, -dx * 40] },
    ...seg(gnd, [x + dx * 2.40, -1.20, z + dz * 2.40], 0.020, mat, 6),           // тяга к плите
    { box: [0.50, 0.14, 0.50, x + dx * 2.40, -1.30, z + dz * 2.40, mat] },       // анкерная плита
  ];
  return out;
}

