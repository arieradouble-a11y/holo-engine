// Анкерный узел: кронштейн-скоба на опоре + клиновой зажим, жгут заводится
// петлёй. На анкерной опоре тяжение пролёта передаётся на опору целиком.
function anker(x, y, z, dx, dz, mat) {
  const nx = x + dx * 0.30, nz = z + dz * 0.30;
  return [
    { box: [0.10, 0.30, 0.10, x + dx * 0.13, y + 0.05, z + dz * 0.13, mat] },  // кронштейн
    { box: [0.20, 0.06, 0.20, x + dx * 0.055, y + 0.16, z + dz * 0.055, mat] },// хомут к стойке
    ...seg([x + dx * 0.13, y + 0.05, z + dz * 0.13], [nx, y, nz], 0.022, mat, 6),
    { box: [0.16, 0.09, 0.09, nx + dx * 0.05, y, nz + dz * 0.05, mat],
      rot: [0, dz ? 90 : 0, 0] },                                              // клиновой зажим
    { sphere: [0.032, nx, y, nz, mat, 8] },                                     // серьга
  ];
}

// Поддерживающий зажим промежуточной опоры: пластиковый корпус, жгут лежит
