// Генератор configs/vl04.json — ВЛИ 0,4 кВ и уличное освещение
//
// Зачем: в музее выстроена вся цепочка «где электричество делают» → ТЭЦ →
// ПС 110/10 кВ → КТП 10/0,4 кВ → ВРУ жилого дома. И между КТП и домом
// ФИЗИЧЕСКИ НИЧЕГО НЕТ: ни опоры, ни провода, ни светильника. При этом именно
// этот участок висит над головой у каждого во дворе, именно на нём происходит
// половина бытовых аварий («оборвало ветром», «перекос фаз», «сгорела техника
// в половине подъезда»), и именно он объясняет, почему уличный фонарь и розетка
// в квартире — это одна и та же линия, но разные фазы и разные хозяева.
//
// Показан фрагмент квартальной ВЛИ: КТП → концевая опора → промежуточная с
// ответвлением к дому → угловая анкерная → пролёт через проезжую часть.
// ВЛИ (изолированная) вместо старой ВЛ с голым алюминием — принципиально:
// у СИП нет траверс и изоляторов, ветка на проводе не даёт короткого замыкания,
// а к магистрали присоединяются НЕ снимая изоляцию (прокалывающий зажим).
//
// Оси: X — вдоль линии, Y — высота (0 = верх покрытия), Z — поперёк улицы
// (дом на −Z, проезжая часть на +Z).
//
// ⚠ ПРОЛЁТЫ СЖАТЫ: реальный пролёт ВЛИ 0,4 кВ — 35–40 м, в модели 7–9 м.
// Иначе объект габаритом 120 м при высоте 10 м превращается в нитку (тот же
// приём, что с укороченной колонной скважины на подземном водозаборе, —
// настоящие значения вынесены в характеристики и подписи узлов).
//
