// Прокалывающий зажим: два болта со СРЫВНОЙ головкой — затягивают до срыва,
// и усилие оказывается ровно паспортным. Зубья прокалывают изоляцию магистрали,
// саму изоляцию при этом не снимают и линию не отключают.
function prokol(p, mat, ax) {
  const a = ax || 'x';
  return [
    { box: [0.075, 0.085, 0.075, p[0], p[1], p[2], mat] },
    { cyl: [0.014, 0.055, p[0], p[1] + 0.062, p[2], mat, 'y', 6] },
    { cyl: [0.019, 0.022, p[0], p[1] + 0.095, p[2], mat, 'y', 6] },           // срывная головка
    { box: [0.03, 0.05, 0.03, p[0] + (a === 'x' ? 0.05 : 0), p[1] - 0.055,
            p[2] + (a === 'x' ? 0 : 0.05), mat] },                            // вывод ответвления
  ];
}

