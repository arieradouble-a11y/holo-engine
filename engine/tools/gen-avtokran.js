//
// Главное, чего не знают жильцы и что объясняет половину «почему так долго»:
// КРАН НЕ ПОДНИМАЕТ ОДИНАКОВО. Его грузоподъёмность зависит от ВЫЛЕТА — чем
// дальше от оси вращения груз, тем меньше масса. На этом объекте стрела стоит
