// точку потока притягиваем к ближайшей вершине нужной части, иначе она садится
// «примерно на корпус», а флоучек честно считает расстояние до металла.
// ⚠ Для стрелы снап применять НЕЛЬЗЯ — она решётчатая, см. выше.
const vertCache = new Map();
function vertsOf(file) {
  if (!vertCache.has(file)) {
    const f = path.join(PARTS_DIR, file);
    vertCache.set(file, fs.existsSync(f) ? glbVerts(f, 2) : []);
  }
  return vertCache.get(file);
}
function snap(p, file) {
  const vs = vertsOf(file);
  let best = p, bd = Infinity;
  for (const v of vs) {
    const d = (v[0] - p[0]) ** 2 + (v[1] - p[1]) ** 2 + (v[2] - (p[2] || 0)) ** 2;
    if (d < bd) { bd = d; best = v; }
  }
  return [+best[0].toFixed(2), +best[1].toFixed(2), +(best[2] || 0).toFixed(2)];
}
