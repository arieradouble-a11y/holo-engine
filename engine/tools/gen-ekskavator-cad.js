// зачем опущены опоры. Разложить донорскую нечем: backcontrol — одна группа из
// безымянных мешей, покомпонентной кинематики (стрела/рукоять/ковш) в ней нет.
//
// Зачем: весь парк музея ездит на одном шасси КамАЗ 6×4 и ничего не копает, а
// любая авария на трубе начинается с землеройной машины. Это она стоит во дворе
// с раскопанной ямой, и это её работу жильцы видят неделю: «когда закопают».
//
// Почему машина такая странная — с ковшом спереди и стрелой сзади: это ДВЕ
// машины в одной. Спереди фронтальный погрузчик (грузить отвал, чистить,
// возить), сзади экскаватор с обратной лопатой (копать на себя). Для аварийной
// бригады это ровно то, что нужно: приехал, вскрыл, выкопал, а потом тем же
// передним ковшом засыпал обратно, не вызывая вторую машину.
//
// Ключевая деталь, которую видно на модели: при копании машина СТОИТ НЕ НА
// КОЛЁСАХ. Сзади её вывешивают выносные опоры, спереди она опирается на
// опущенный ковш погрузчика — иначе усилие на зубьях раскачивало бы её на
// подвеске, и точность копания рядом с чужими коммуникациями была бы нулевой.
//
// ДОНОР: JCB backhoe loader (Sketchfab, CC BY 4.0, sarvesh12). Взяты кузов с
// кабиной и капотом, колёса и фронтальный погрузчик — то, что процедурой из
// коробок не набрать (замечание пользователя «слишком квадратно»). Машина у
// донора уже стоит в РАБОЧЕМ положении: аутригеры опущены на грунт, ковш
// погрузчика лежит на земле — ровно та поза, ради которой объект и делался.
// Своими остались обратная лопата, гидравлика, свет и место работ.
