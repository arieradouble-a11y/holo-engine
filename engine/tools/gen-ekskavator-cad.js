// ---- зеркалирование по Z (то же, что в kamaz-6x4.js) -------------------------
const ZI = { box: 5, cyl: 4, frustum: 5, sphere: 3, torus: 4, capsule: 4 };
function negZ(it) {
  const o = {};
  for (const k of Object.keys(it)) {
    if (k === 'items') o.items = it.items.map(negZ);
    else if (k === 'at' || k === 'step') o[k] = [it[k][0], it[k][1], -it[k][2]];
    else if (k === 'rot' || k === 'rstep') o[k] = [-it[k][0], -it[k][1], it[k][2]];
    else if (k === 'tube') o.tube = [it.tube[0], it.tube[1].map(p => [p[0], p[1], -p[2]]), ...it.tube.slice(2)];
    else if (ZI[k] != null) { const a = it[k].slice(); a[ZI[k]] = -a[ZI[k]]; o[k] = a; }
    else o[k] = it[k];
  }
  return o;
}
const mir = items => [...items, ...items.map(negZ)];

// ---- балка по отрезку A→B в плоскости XY -------------------------------------
// Поворот вокруг Z на угол −atan2(dx,dy) переводит собственную ось Y детали в
// направление A→B: так стрелы и цилиндры задаются двумя точками, а не подбором
// углов на глаз (подбором они и разъезжались в первых заходах).
const ang = (a, b) => -Math.atan2(b[0] - a[0], b[1] - a[1]) * 180 / Math.PI;
const len = (a, b) => Math.hypot(b[0] - a[0], b[1] - a[1]);
const mid = (a, b, t) => [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t];

function balka(a, b, w, th, z, mat, extra) {
  const c = mid(a, b, 0.5), L = len(a, b);
  return [{ box: [th, L, w, c[0], c[1], z, mat], rot: [0, 0, ang(a, b)] },
    ...(extra === false ? [] : [
      { cyl: [w * 0.42, th * 1.25, a[0], a[1], z, mat, 'z', 12] },              // проушина у пяты
      { cyl: [w * 0.42, th * 1.25, b[0], b[1], z, mat, 'z', 12] }])];           // проушина у головы
}

// Гидроцилиндр: корпус, шток, проушины с пальцами. Шток намеренно тоньше и
// светлее корпуса — именно по паре «толстая гильза + тонкий шток» цилиндр
// узнаётся в каркасе, а без этого он читается просто трубой.
function cilindr(a, b, r, mat, part) {
  const L = len(a, b), A = ang(a, b), t = part == null ? 0.55 : part;
  const c1 = mid(a, b, t / 2), c2 = mid(a, b, 1 - (1 - t) / 2);
  return [
    { cyl: [r, L * t, c1[0], c1[1], 0, mat, 'y', 14], rot: [0, 0, A] },         // гильза
    { cyl: [r * 0.52, L * (1 - t) + 0.06, c2[0], c2[1], 0, mat + '-dark', 'y', 12], rot: [0, 0, A] },  // шток
    { cyl: [r * 1.14, 0.07, mid(a, b, t)[0], mid(a, b, t)[1], 0, mat, 'y', 14], rot: [0, 0, A] },  // грундбукса
    { torus: [r * 0.9, r * 0.28, a[0], a[1], 0, mat, 'z'] },                    // проушина гильзы
    { torus: [r * 0.62, r * 0.22, b[0], b[1], 0, mat + '-dark', 'z'] },         // проушина штока
    { cyl: [r * 0.3, r * 1.2, a[0], a[1], 0, mat + '-dark', 'z', 10] },         // палец
    { cyl: [r * 0.24, r * 1.0, b[0], b[1], 0, mat + '-dark', 'z', 10] },
  ];
}
// цилиндр в плоскости z = zc (пара — через mir)
const cil = (a, b, r, mat, zc, part) => [{ at: [0, 0, zc], items: cilindr(a, b, r, mat, part) }];

