// Генератор configs/k700.json — тяжёлый трактор с бульдозерным отвалом
// на рабочей карте полигона ТКО.
//
//   blender -b --factory-startup -P tools/donor-split.py -- \
//           --in ../kirovets_k-700.glb --out ../k700-parts \
//           --wheel-mat wheel_wheel --nose-mat none --flip --scale 1 --anchor-x 0 --tris 45000 \
//           --group wheel_wheel:part01 --group vehicle_shaft:part02 --group '*':part00
//   node tools/gen-k700.js && node build.js --config configs/k700.json --parts ../k700-parts
//
// Зачем: у объекта «Полигон и сортировка ТКО» есть узел «Уплотнение и рабочая
// карта» — а машины, которая это делает, в музее не было. Мусорная цепочка
// доходила до ворот полигона и там обрывалась: контейнерная площадка →
// мусоровоз → бункеровоз → весовая → и дальше пусто. Здесь она замыкается.
//
// Что узнаёт житель. Полигон — не куча, а СООРУЖЕНИЕ, которое строят слоями:
// привезённое за день сдвигают на карту, разравнивают, уплотняют проходами
// тяжёлой машины и пересыпают грунтом. Уплотнение даёт коэффициент три-четыре:
// то, что заняло бы гектары, умещается на карте и растёт ВВЕРХ. Пересыпка не
// косметика — она держит запах, птиц, разлёт мусора ветром и, главное, не даёт
// разгореться телу полигона: горит он не сверху, а внутри.
//
// Донор: К-700 «Кировец» (Sketchfab, CC BY 4.0, dugito03) — модель 1:1 в метрах
// (колесо ⌀1.699 против паспортных 1.7). Машина шарнирно-сочленённая: на рыхлых
// отходах это выигрыш, потому что поворот идёт всей машиной, без вывешивания
// передних колёс.
//
// Система координат: X — вдоль машины (+X нос и отвал), Y — высота (0 = верх
// уплотнённого слоя, по которому идёт машина), Z — поперёк.
