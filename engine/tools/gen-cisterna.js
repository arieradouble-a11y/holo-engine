// Зачем: водяная цепочка музея показана целиком — водозабор, станции, башня,
// сети, дом, — но только в исправном состоянии. А житель чаще всего сталкивается
// с ней в момент, когда воды НЕТ: сеть в аварии, дом отключён, и во двор
// приезжает вот эта машина. Подвоз воды при длительном отключении — обязанность
// организации, отключившей ресурс, и цистерна оказывается последним звеном
// водоснабжения, когда все остальные звенья не работают.
//
// Чем она отличается от поливомоечной, которая в музее уже есть: у той цистерна
// техническая и вода в ней непитьевая. Здесь ПИЩЕВАЯ ёмкость — своя, только под
// воду, с санитарной обработкой и пломбами перед рейсом, с раздаточными кранами
// и поддоном. Использовать её под что-то другое нельзя: обратно в пищевую она
// уже не вернётся.
//
// Ещё одна вещь, которую видно только на разрезе: ВОЛНОРЕЗЫ. Восемь тонн воды
// в гладкой бочке при торможении бьют в переднее днище и толкают машину — от
// этого и ограничение скорости, и перегородки внутри.
//
