// (река → колодец → НС-I → смесители → камеры хлопьеобразования → отстойники),
// вторая разворачивается на север и идёт обратно (фильтровальный зал → УФ и
// хлораторная → РЧВ → НС-II → магистраль). Такая складка вдвое укорачивает
// габарит против прямой линии, а вертикали (бак промывной воды 12 м, мачты
