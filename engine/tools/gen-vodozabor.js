// камеры хлопьеобразования отсутствовали вовсе, а между технологическими
// блоками не было НИ ОДНОЙ соединительной трубы: стрелки потоков летели по
// воздуху над пустотой. Самая высокая точка — 8,5 м, поэтому объект читался
