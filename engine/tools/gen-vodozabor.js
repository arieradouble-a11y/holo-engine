// Лестничный марш: два косоура, восемь ступеней и поручни. Kit-овая lestnica()
// набирает ступени по натурному подъёму 0,19 м — на марше в машзал глубиной 7 м
// это полсотни примитивов, то есть целая система бюджета на одну лестницу.
const marsh = (x, y0, z, h, mat, o) => {
  const opt = o || {}, run = opt.run || h * 0.9, w = opt.w || 0.9, n = 8;
  const ang = Math.atan2(h, run) * 180 / Math.PI, L = Math.hypot(run, h);
  return [
    { at: [x + run / (2 * n), y0 + h / n, z], repeat: n, step: [run / n, h / n, 0], items: [
      { box: [run / n * 0.95, 0.05, w, 0, 0, 0, mat] },                            // ступени
    ]},
    { box: [L, 0.16, 0.06, x + run / 2, y0 + h / 2, z - w / 2, mat], rot: [0, 0, ang] },
    { box: [L, 0.16, 0.06, x + run / 2, y0 + h / 2, z + w / 2, mat], rot: [0, 0, ang] },
    { box: [L, 0.05, 0.05, x + run / 2, y0 + h / 2 + 1.0, z - w / 2, mat], rot: [0, 0, ang] },
    { box: [L, 0.05, 0.05, x + run / 2, y0 + h / 2 + 1.0, z + w / 2, mat], rot: [0, 0, ang] },
    { box: [0.05, 1.0, 0.05, x + run * 0.5, y0 + h * 0.5 + 0.5, z - w / 2, mat] },
    { box: [0.05, 1.0, 0.05, x + run * 0.5, y0 + h * 0.5 + 0.5, z + w / 2, mat] },
  ];
};

