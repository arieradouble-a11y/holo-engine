g.push(...HK.kanalizaciya({ W, D, sections: B.sections, sw: B.sectionWidth, yFloor, yK, zKan, rKan: 0.06, rOut: 0.085 }));
g.push(...pipe([[risX('sewer'), yCeil - 0.05, zRis], [risX('sewer'), yK + 0.30, zRis],
  [risX('sewer'), yK + 0.30, zKan], [risX('sewer'), yK, zKan]], 0.06, 'kanal'));
