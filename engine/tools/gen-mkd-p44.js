// ═══ НЕЗАДЫМЛЯЕМАЯ ЛЕСТНИЦА Н1: ВОЗДУШНЫЕ ПЕРЕХОДЫ ═══════════════════════════
// С этажа выходишь НА УЛИЦУ и только оттуда — в лестничную клетку. Между
