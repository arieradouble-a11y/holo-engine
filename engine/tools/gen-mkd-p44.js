  g.push({ box: [0.62, 0.72, 0.24, risX('fire') + 0.5, f * B.floorHeight + 1.3, zRis, 'pozhar'] },
    { box: [0.30, 0.16, 0.012, risX('fire') + 0.5, f * B.floorHeight + 1.55, zRis + 0.13, 'pozhar-lamp'] });

