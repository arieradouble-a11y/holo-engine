g.push(...pipe([[risX('electric'), yCeil - 0.35, zRis], [risX('electric'), yCeil - 0.35, D * 0.26]], 0.035, 'vru'));

// ═══ НАСОСНЫЕ: ХОЗЯЙСТВЕННАЯ И ПОЖАРНАЯ ══════════════════════════════════════
