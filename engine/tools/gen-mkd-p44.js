g.push(...pipe([[risX('water') + 0.4, yG, zWat], [risX('water') + 0.4, yG + 0.25, zWat],
  [risX('water') + 0.4, yG + 0.25, zRis], [risX('water') + 0.4, yCeil - 0.05, zRis]], rGvs, 'hvs'));

