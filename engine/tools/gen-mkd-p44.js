// пуска в стволе на семнадцатом этаже давления нет.
const xNas = 12.0, zNas = 3.4;
[-0.95, 0.95].forEach(dz => {
  g.push(...nasos(xNas, yFloor + 0.72, zNas + dz, 'nas', { dn: 0.075, frameH: 0.24 }));
  g.push(...pipe([[xNas - 0.25, yFloor + 0.72, zNas + dz], [xNas - 0.25, yFloor + 0.72, zNas + dz * 2.0]], 0.048, 'nas'));
  g.push(...pipe([[xNas, yFloor + 1.02, zNas + dz], [xNas, yFloor + 1.62, zNas + dz]], 0.048, 'nas'));
  g.push(...obratnyi(xNas, yFloor + 1.28, zNas + dz, 0.048, 'nas', 'y'));
  g.push(...zadvizhka(xNas - 0.25, yFloor + 0.72, zNas + dz * 2.0, 0.048, 'nas', 'z'));
});
g.push(...pipe([[xNas, yFloor + 1.62, zNas - 0.95], [xNas, yFloor + 1.62, zNas + 0.95]], 0.055, 'nas'));
g.push(...pipe([[xNas, yFloor + 1.62, zNas], [xNas, yW, zNas], [xNas, yW, zWat]], 0.055, 'nas'));
g.push(...pipe([[xNas - 0.25, yFloor + 0.72, zNas], [xNas - 2.2, yFloor + 0.72, zNas],
  [xNas - 2.2, yW, zNas], [xNas - 2.2, yW, zWat]], 0.048, 'nas'));
g.push(...manometr(xNas + 0.14, yFloor + 1.78, zNas, 'nas'));
g.push(...bak(xNas + 2.0, yFloor, zNas, 'nas', { r: 0.32, h: 1.1, floor: yFloor, ladder: false, seg: 14 }));
g.push(...pipe([[xNas + 2.0, yFloor + 0.14, zNas], [xNas + 2.0, yFloor + 0.14, zNas - 1.3],
  [xNas, yFloor + 0.14, zNas - 1.3], [xNas, yFloor + 0.72, zNas - 1.3]], 0.032, 'nas'));
g.push(...shkaf(xNas - 1.2, yFloor, zNas - 2.6, 'nas', { w: 0.9, h: 1.6, d: 0.32, floor: yFloor }));
// пожарные насосы и стояк
const xPozh = 18.5, zPozh = 3.4;
