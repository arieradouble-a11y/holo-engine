// Генератор configs/mkd-p44.json — панельная 17-этажка серии П-44.
//
//   node tools/gen-mkd-p44.js && node build.js --config configs/mkd-p44.json --check
//
// Зачем: между девятиэтажкой и монолитной высоткой в музее был провал, а именно
// в нём живёт самый массовый «высокий» дом позднесоветских кварталов. И разница
// с девятиэтажкой опять не в этажах, а в решениях, которые появляются, когда
// дом переваливает за девять:
//
//  • ТЁПЛЫЙ ЧЕРДАК. Вытяжка из квартир не идёт отдельной шахтой на кровлю у
//    каждого стояка: каналы обрываются в общем объёме утеплённого чердака, и
//    оттуда воздух уходит ОДНОЙ шахтой на секцию. Отсюда и особенность жалоб:
//    «дует из вентиляции у соседа» в таком доме — это про общий чердак.
//  • НЕЗАДЫМЛЯЕМАЯ ЛЕСТНИЦА ТИПА Н1. Попасть на неё можно только через открытый
//    воздушный переход: с этажа выходишь на улицу и лишь потом в лестничную
//    клетку. Дым в неё не заходит физически, потому что между лестницей и
//    квартирами нет закрытого объёма. Застеклить этот переход нельзя.
//  • ДВА ЛИФТА, МУСОРОПРОВОД, ПОЖАРНЫЙ ВОДОПРОВОД С НАСОСАМИ и повысительная
//    насосная холодной воды: городского напора на семнадцатый этаж не хватает.
//
// Система координат: X — длина дома, Y — высота (0 = пол первого этажа),
// Z — глубина (лицевой фасад +Z, тыльный −Z; воздушные переходы на тыльном).
