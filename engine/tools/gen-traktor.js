// Генератор configs/traktor.json — коммунальный трактор с отвалом и щёткой.
//
//   blender -b --factory-startup -P tools/donor-split.py -- \
//           --in ../mtz-80_belarus.glb --out ../traktor-parts \
//           --group Frame,Wheel:part00 --group Engine:part01 --group Body,Glass:part02 \
//           --wheelbase 2.45 --rear-axle -1.23 --tris 60000
//   node tools/gen-traktor.js
//   node build.js --config configs/traktor.json --parts ../traktor-parts
//
// Зачем объект: весь парк музея — тяжёлые машины на шасси КамАЗ, которые
// работают на улицах. А двор убирает не они: во двор КамАЗ с отвалом просто не
// заедет — между припаркованными машинами и детской площадкой нужен радиус
// разворота, которого у него нет. Двор — это всегда трактор.
//
// Это же и граница ответственности, из-за которой чаще всего спорят жильцы:
// проезжую часть улицы убирает город своей техникой, а ДВОР — управляющая
// организация, своим или наёмным трактором, и оплачивается это строкой
// «содержание общего имущества». Отсюда классическое «улицу почистили, а во
// двор не заехали»: это не халатность одной службы, а две разные службы.
//
// ПОЧЕМУ ТЕЛО ДОНОРСКОЕ. Первая версия была набрана целиком примитивами и
// читалась игрушкой: трактор узнают не по габариту, а по скруглениям — круглые
// арки крыльев, сужающийся капот, гнутые стёкла кабины, — а их из коробок не
// набрать. Поэтому здесь тот же приём, что у всего парка КамАЗов: ТЕЛО берётся
// из донорской модели (МТЗ-80, Sketchfab, CC BY 4.0), а всё, ради чего объект
// существует, — навеска, щётка, отвал, гидравлика — остаётся процедурным и
// разбирается на системы. Донор совмещается с нашей системой координат по ОСЯМ
// КОЛЁС (tools/donor-split.py), а не по габаритной коробке.
//
// Система координат: X — вдоль машины (+X нос), Y — высота (0 = грунт),
// Z — поперёк. Навеска и гидравлика строятся хелперами по отрезкам A→B.
