// Генератор configs/traktor.json — коммунальный трактор с отвалом и щёткой.
//
//   node tools/gen-traktor.js && node build.js --config configs/traktor.json --check
//
// Зачем: весь парк музея — тяжёлые машины на шасси КамАЗ, которые работают на
// улицах. А двор убирает не они: во двор КамАЗ с отвалом просто не заедет —
// между припаркованными машинами и детской площадкой нужен радиус разворота,
// которого у него нет. Двор — это всегда трактор: небольшой, полноприводный,
// с отвалом спереди и щёткой сзади.
//
// Это же и граница ответственности, из-за которой чаще всего спорят жильцы:
// проезжую часть улицы убирает город своей техникой, а ДВОР — управляющая
// организация, своим или наёмным трактором, и оплачивается это строкой
// «содержание общего имущества». Отсюда классическое «улицу почистили, а во
// двор не заехали»: это не халатность одной службы, а две разные службы.
//
// Что важно понимать про саму машину: щётка МЕТЁТ, но не скалывает — наледь она
// только полирует, под неё нужен реагент или скол. И крутит её не колесо, а вал
// отбора мощности прямо от двигателя, поэтому щётка работает одинаково и на
// ходу, и на месте.
//
// Система координат: X — вдоль машины (+X нос), Y — высота (0 = грунт),
// Z — поперёк. Навеска и гидравлика строятся хелперами по отрезкам A→B.
