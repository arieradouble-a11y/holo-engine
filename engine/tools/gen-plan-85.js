  wx(6.95, X[1], X[2], .12, 'partitions');                                // холл 5,54 (3Б) | гостиная 17,93 и санузлы (2Б)
  // 2Б: гостиная 17,93 (Бс, 5,10), кухня 7,48 (Бс, 2,91), холл 3,59, санузел 2,58 + уборная 1,26
