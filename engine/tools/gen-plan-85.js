  wx(5.9, 7.04, 8.6, .08, 'wet'); wz(8.6, 4.6, 6.95, .08, 'wet', [door(0.7, .65), door(1.85, .65)]);
  wx(5.25, 7.04, 8.6, .065, 'wet');                                       // ванная | уборная
