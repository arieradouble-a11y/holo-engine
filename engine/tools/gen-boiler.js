// Маршевая лестница: та же схема, что в ките, но экономнее — на подъёме 4,4 м
// штатная lestnica() отдаёт 35 примитивов только на один марш.
const marsh = (x, y0, z, h, mat, run, wid) => {
  const n = 10, dx = run / n, dy = h / n;
  const ang = Math.atan2(h, run) * 180 / Math.PI, L = Math.hypot(run, h);
  return [
    { at: [x + dx / 2, y0 + dy, z], repeat: n, step: [dx, dy, 0], items: [
      { box: [dx * 0.95, 0.04, wid, 0, 0, 0, mat] },                                   // ступень
    ]},
    { at: [x + run / 2, y0 + h / 2, z - wid / 2], repeat: 2, step: [0, 0, wid], items: [
      { box: [L, 0.14, 0.05, 0, 0, 0, mat], rot: [0, 0, ang] },                        // косоур
      { box: [L, 0.05, 0.05, 0, 1.0, 0, mat], rot: [0, 0, ang] },                      // поручень
      { box: [0.05, 1.0, 0.05, 0, h * 0.5, 0, mat] },                                  // стойка перил
    ]},
  ];
};

